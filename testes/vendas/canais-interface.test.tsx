// @vitest-environment jsdom
import React from "react";
import { afterEach, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
const sim = vi.hoisted(() => ({ salvar: vi.fn() }));
vi.mock("next/navigation", () => ({ useRouter: () => ({ refresh: vi.fn() }) }));
vi.mock("@/app/(protegido)/vendas/canais/actions", () => ({ salvarCanalVendaAction: sim.salvar }));
import { CanaisVenda } from "@/app/(protegido)/vendas/canais/canais-client";
const canais = [{ id: "site", nome: "SITE", versao: 1, categoriaReceitaId: null, categoriaReceita: null }];
const categorias = [{ id: "receita-site", nome: "Receitas de vendas / Site e encomendas com nome longo", grupo: "RECEITA_BRUTA" as const }];
afterEach(() => { cleanup(); vi.clearAllMocks(); });
it("salva nome e categoria explicitamente, preserva rascunho após conflito e reutiliza chave na repetição", async () => {
  const usuario = userEvent.setup();
  sim.salvar.mockResolvedValue({ erro: "O canal mudou. Reabra para conferir antes de salvar." });
  render(<CanaisVenda canais={canais} categorias={categorias} editar />);
  expect(screen.getByText("Categoria não configurada")).toBeTruthy();
  await usuario.click(screen.getByRole("button", { name: "Editar canal SITE" }));
  expect((screen.getByLabelText("Nome do canal") as HTMLInputElement).readOnly).toBe(false);
  expect((screen.getByRole("button", { name: "Salvar" }) as HTMLButtonElement).disabled).toBe(true);
  fireEvent.change(screen.getByLabelText("Nome do canal"), { target: { value: "ENCOMENDAS" } });
  await usuario.click(screen.getByRole("combobox", { name: "Categoria de receita do canal" }));
  await usuario.click(await screen.findByRole("option", { name: categorias[0].nome }));
  fireEvent.blur(screen.getByRole("combobox", { name: "Categoria de receita do canal" }));
  expect(sim.salvar).not.toHaveBeenCalled();
  await usuario.click(screen.getByRole("button", { name: "Salvar" }));
  expect((await screen.findByRole("alert")).textContent).toContain("O canal mudou");
  expect((screen.getByLabelText("Nome do canal") as HTMLInputElement).value).toBe("ENCOMENDAS");
  expect((screen.getByRole("combobox", { name: "Categoria de receita do canal" }) as HTMLInputElement).value).toBe(categorias[0].nome);
  const primeira = sim.salvar.mock.calls[0][0];
  expect(primeira).toMatchObject({ id: "site", versao: 1, nome: "ENCOMENDAS", categoriaReceitaId: "receita-site" });
  await usuario.click(screen.getByRole("button", { name: "Salvar" }));
  expect(sim.salvar.mock.calls[1][0].chave).toBe(primeira.chave);
});
it("bloqueia repetição e fechamento enquanto salva; consulta não oferece edição", async () => {
  const usuario = userEvent.setup();
  let concluir!: (r: { ok: true }) => void;
  sim.salvar.mockImplementation(() => new Promise(resolve => { concluir = resolve; }));
  const configurado = [{ ...canais[0], categoriaReceitaId: categorias[0].id, categoriaReceita: { nome: categorias[0].nome } }];
  const view = render(<CanaisVenda canais={configurado} categorias={categorias} editar />);
  expect(screen.getByText(categorias[0].nome)).toBeTruthy();
  await usuario.click(screen.getByRole("button", { name: "Editar canal SITE" }));
  await usuario.click(screen.getByRole("button", { name: "Salvar" }));
  expect((screen.getByRole("button", { name: "Salvando…" }) as HTMLButtonElement).disabled).toBe(true);
  await usuario.keyboard("{Escape}");
  expect(screen.getByRole("dialog")).toBeTruthy();
  concluir({ ok: true });
  await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
  view.unmount();
  render(<CanaisVenda canais={canais} categorias={categorias} editar={false} />);
  expect(screen.queryByRole("button", { name: /Editar canal|Novo canal/ })).toBeNull();
});
