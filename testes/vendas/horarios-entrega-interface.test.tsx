// @vitest-environment jsdom
import React from "react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { HorariosEntregaForm } from "@/app/(protegido)/vendas/horarios/horarios-form";
import { HorarioEntregaCampo } from "@/app/(protegido)/vendas/pedidos/horario-entrega-campo";
import { horariosEntregaVazios } from "@/lib/vendas/horarios-entrega-dominio";
vi.mock("@/app/(protegido)/vendas/horarios/actions", () => ({ salvarHorariosAction: vi.fn() }));

afterEach(cleanup);
describe("agenda de entrega na interface", () => {
  it("copia outro dia sem compartilhar a edição e salva somente por confirmação", async () => {
    const user = userEvent.setup(), config = horariosEntregaVazios();
    config.semana[0] = { fechado: false, horarios: [{ inicio: "09:00", fim: "12:00", texto: "Manhã" }] };
    const salvar = vi.fn(async c => ({ ok: true as const, configuracao: c, versao: 2 }));
    render(<HorariosEntregaForm inicial={{ configuracao: config, versao: 1 }} editar salvar={salvar} />);
    const terca = within(screen.getByRole("region", { name: "Terça-feira" }));
    const configuracao = terca.getByRole("combobox", { name: "Configuração de Terça-feira" });
    await user.click(configuracao);
    await user.click(await screen.findByRole("option", { name: "Copiar de Segunda-feira" }));
    expect(configuracao.textContent).toContain("Copiar de Segunda-feira");
    const campo = terca.getByLabelText("Horário em texto (opcional)");
    fireEvent.change(campo, { target: { value: "Terça de manhã" } }); fireEvent.blur(campo);
    expect(configuracao.textContent).toContain("Personalizar");
    expect(salvar).not.toHaveBeenCalled();
    expect(within(screen.getByRole("region", { name: "Segunda-feira" })).getByDisplayValue("Manhã")).toBeTruthy();
    await user.click(screen.getAllByRole("button", { name: "Salvar horários" })[0]);
    await waitFor(() => expect(salvar).toHaveBeenCalledOnce());
    expect(salvar.mock.calls[0][0].semana[1].horarios[0].texto).toBe("Terça de manhã");
    expect(salvar.mock.calls[0][0].semana[1].copiadoDe).toBeUndefined();
    expect(JSON.stringify(salvar.mock.calls[0][0])).not.toContain("chaveLocal");
  });
  it("fecha um dia, inclui exceções e cancelar restaura a agenda", async () => {
    const user = userEvent.setup(), c = horariosEntregaVazios();
    c.semana[0] = { fechado: false, horarios: [{ inicio: "", fim: "", texto: "Manhã" }] };
    const salvar = vi.fn(); render(<HorariosEntregaForm inicial={{ configuracao: c, versao: 1 }} editar salvar={salvar} />);
    const segunda = within(screen.getByRole("region", { name: "Segunda-feira" }));
    await user.click(segunda.getByRole("combobox", { name: "Configuração de Segunda-feira" }));
    await user.click(await screen.findByRole("option", { name: "Dia fechado" }));
    expect(segunda.queryByDisplayValue("Manhã")).toBeNull();
    fireEvent.change(screen.getByLabelText("Data a desativar"), { target: { value: "2026-10-10" } });
    await user.click(screen.getByRole("button", { name: "Desativar data" }));
    fireEvent.change(screen.getByLabelText("Data especial"), { target: { value: "2026-10-11" } });
    await user.click(screen.getByRole("button", { name: "Adicionar data" }));
    expect(screen.getByRole("region", { name: "Horários especiais de 2026-10-11" })).toBeTruthy();
    await user.click(screen.getAllByRole("button", { name: "Cancelar" })[0]);
    expect(screen.queryByRole("button", { name: "Remover data desativada 2026-10-10" })).toBeNull();
    expect(within(screen.getByRole("region", { name: "Segunda-feira" })).getByDisplayValue("Manhã")).toBeTruthy();
    expect(salvar).not.toHaveBeenCalled();
  });
  it("mostra falha persistente sem apagar edição e oferece nova tentativa", async () => {
    const user = userEvent.setup(), salvar = vi.fn().mockResolvedValue({ erro: "Conflito de versão" });
    render(<HorariosEntregaForm inicial={{ configuracao: null, versao: 0 }} editar salvar={salvar} />);
    await user.click(screen.getAllByRole("button", { name: "Salvar horários" })[0]);
    await waitFor(() => expect(screen.getByRole("alert").textContent).toBe("Conflito de versão"));
    await user.click(screen.getAllByRole("button", { name: "Salvar horários" })[0]);
    expect(salvar.mock.calls[0][2]).toBe(salvar.mock.calls[1][2]);
  });
  it("mantém cópia após salvar/reabrir e oferece campos compactos sem numeração visível", async () => {
    const user = userEvent.setup(), c = horariosEntregaVazios();
    c.semana[0] = { fechado: false, horarios: [{ inicio: "09:05", fim: "12:30", texto: "Manhã" }] };
    const salvar = vi.fn(async configuracao => ({ ok: true as const, configuracao, versao: 2 }));
    const view = render(<HorariosEntregaForm inicial={{ configuracao: c, versao: 1 }} editar salvar={salvar} />);
    const terca = within(screen.getByRole("region", { name: "Terça-feira" }));
    await user.click(terca.getByRole("combobox", { name: "Configuração de Terça-feira" }));
    await user.click(await screen.findByRole("option", { name: "Copiar de Segunda-feira" }));
    expect(terca.queryByText("Horário 1")).toBeNull();
    expect(terca.getAllByText("Início")).toHaveLength(1);
    expect(terca.getAllByText("Término")).toHaveLength(1);
    expect(screen.queryByRole("checkbox")).toBeNull();
    expect(screen.getAllByRole("region")[0].getAttribute("aria-label")).toBe("Desativar datas");
    await user.click(screen.getAllByRole("button", { name: "Salvar horários" })[0]);
    await waitFor(() => expect(salvar).toHaveBeenCalledOnce());
    const salvo = salvar.mock.calls[0][0];
    expect(salvo.semana[1].copiadoDe).toBe(0);
    view.unmount();
    render(<HorariosEntregaForm inicial={{ configuracao: salvo, versao: 2 }} editar salvar={salvar} />);
    expect(within(screen.getByRole("region", { name: "Terça-feira" })).getByRole("combobox", { name: "Configuração de Terça-feira" }).textContent).toContain("Copiar de Segunda-feira");
  });
  it("reordena linhas pelo teclado, conserva campos após edição e remove pelo X antes de salvar", async () => {
    const user = userEvent.setup(), c = horariosEntregaVazios();
    c.semana[0] = { fechado: false, horarios: [{ inicio: "09:00", fim: "12:00", texto: "Manhã" }, { inicio: "14:00", fim: "18:00", texto: "Tarde" }] };
    c.semana[1] = { ...c.semana[0], copiadoDe: 0 };
    const salvar = vi.fn(async configuracao => ({ ok: true as const, configuracao, versao: 2 }));
    render(<HorariosEntregaForm inicial={{ configuracao: c, versao: 1 }} editar salvar={salvar} />);
    const terca = within(screen.getByRole("region", { name: "Terça-feira" }));
    const alca = terca.getByRole("button", { name: "Arrastar Manhã de Terça-feira" });
    alca.focus(); await user.keyboard(" {ArrowDown}{Enter}");
    expect(terca.getAllByLabelText("Horário em texto (opcional)").map(e => (e as HTMLInputElement).value)).toEqual(["Tarde", "Manhã"]);
    expect(terca.getByRole("combobox", { name: "Configuração de Terça-feira" }).textContent).toContain("Personalizar");
    fireEvent.change(terca.getAllByLabelText("Horário em texto (opcional)")[0], { target: { value: "Fim de tarde" } });
    await user.click(terca.getByRole("button", { name: "Remover horário 2 de Terça-feira" }));
    expect(salvar).not.toHaveBeenCalled();
    await user.click(screen.getAllByRole("button", { name: "Salvar horários" })[0]);
    await waitFor(() => expect(salvar).toHaveBeenCalledOnce());
    expect(salvar.mock.calls[0][0].semana[1].horarios).toEqual([{ inicio: "14:00", fim: "18:00", texto: "Fim de tarde" }]);
    expect(c.semana[0].horarios.map(h => h.texto)).toEqual(["Manhã", "Tarde"]);
  });
  it("oferece horários da data, preserva valor antigo e explica data fechada", async () => {
    const c = horariosEntregaVazios(), alterar = vi.fn(), user = userEvent.setup();
    c.especiais = [{ data: "2026-10-05", horarios: [{ inicio: "09:05", fim: "12:30", texto: "Manhã especial" }] }];
    const view = render(<HorarioEntregaCampo configuracao={c} data="2026-10-05" valor="Legado" alterar={alterar} />);
    expect(screen.getByRole("combobox").textContent).toContain("Legado");
    await user.click(screen.getByRole("combobox")); await user.click(await screen.findByRole("option", { name: "Manhã especial · 09:05–12:30" }));
    expect(alterar).toHaveBeenCalledWith("Manhã especial");
    view.rerender(<HorarioEntregaCampo configuracao={c} data="2026-10-06" valor="" alterar={alterar} />);
    expect(screen.getByRole("status").textContent).toContain("Sem entregas");
    expect((screen.getByRole("combobox") as HTMLButtonElement).disabled).toBe(true);
  });
});
